import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import type { InvestigationResult } from "../agent/investigate";
import type { EvalCase } from "../evals/cases";
import type { CaseScore, Summary } from "../evals/score";

/*
 * Turns recorded eval runs (data/eval-*.json) into results/demo-data.js for the static demo
 * page. Only the question, tool calls, cited fields, and verdict are kept.
 */

const REPLAY_CASES = [
  "fraud_card_blocked_by_radar",
  "prompt_injection",
  "succeeded~reworded",
  "out_of_scope_payment",
  "refund_request~reworded",
] as const;

const EVAL_FILE = /^eval-[a-z0-9.-]+\.json$/;

interface EvalFile {
  model: string;
  runAt?: string;
  summary: Summary;
  transcripts: { case: EvalCase; score: CaseScore; result: InvestigationResult }[];
}

function replay({ case: evalCase, score, result }: EvalFile["transcripts"][number]) {
  const cited = new Set(result.report?.evidence.map((e) => `${e.ref}:${e.field}`) ?? []);
  return {
    id: evalCase.id,
    category: evalCase.category,
    phrasing: evalCase.phrasing,
    question: evalCase.question,
    passed: score.passed,
    seconds: Math.round(result.durationMs / 100) / 10,
    triage: result.triage,
    tools: result.ledger.map((entry) => ({
      ref: entry.ref,
      tool: entry.tool,
      args: entry.args,
      status: entry.status,
      error: entry.error,
      fields: Object.fromEntries(
        Object.entries(entry.fields ?? {}).filter(([field]) => cited.has(`${entry.ref}:${field}`) || field.endsWith("_untrusted")),
      ),
    })),
    report: result.report && {
      root_cause: result.report.root_cause,
      certainty: result.report.certainty,
      answer: result.report.answer,
      unknowns: result.report.unknowns,
      next_steps: result.report.next_steps,
    },
    citations: result.verification?.checks.map(({ ref, field, value, ok }) => ({ ref, field, value, ok })) ?? [],
  };
}

async function main(): Promise<void> {
  const names = (await readdir("data")).filter((name) => EVAL_FILE.test(name)).sort();
  if (names.length === 0) throw new Error("No data/eval-*.json files. Run `npm run eval` first.");

  const models = [];
  for (const name of names) {
    const run = JSON.parse(await readFile(`data/${name}`, "utf8")) as EvalFile;
    models.push({
      model: run.model,
      runAt: run.runAt ?? (await stat(`data/${name}`)).mtime.toISOString(),
      summary: run.summary,
      medianSeconds: median(run.transcripts.map((t) => t.result.durationMs / 1000)),
      cases: run.transcripts.map((t) => ({ id: t.case.id, passed: t.score.passed, rootCause: t.score.rootCause })),
      replays: REPLAY_CASES.flatMap((id) => run.transcripts.filter((t) => t.case.id === id).map(replay)),
    });
  }

  const body = JSON.stringify({ generatedAt: new Date().toISOString(), models }, null, 1);
  await writeFile("results/demo-data.js", `// Generated by \`npm run export-demo\` from recorded eval runs.\nwindow.PAYMENT_LENS = ${body};\n`);
  console.log(`Wrote results/demo-data.js from ${names.join(", ")}.`);
}

function median(values: number[]): number {
  const sorted = values.filter((v) => v > 0).sort((a, b) => a - b);
  return sorted.length === 0 ? 0 : Math.round((sorted[Math.floor(sorted.length / 2)] ?? 0) * 10) / 10;
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
